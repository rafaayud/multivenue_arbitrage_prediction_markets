_DEFAULT_PORTFOLIO_ID = STRATEGY_PORTFOLIO_ID
_MANUAL_RESOLUTION_PREFIX = "manual-resolution:"


def manual_resolution_client_order_id(execution_id: str) -> ClientOrderID:
    """Return the stable accounting identifier for one operator resolution.

    Parameters
    ----------
    execution_id : str
        Parent execution identity.

    Returns
    -------
    ClientOrderID
        Identifier used to load the manual trade with the execution fills.
    """
    return ClientOrderID(f"{_MANUAL_RESOLUTION_PREFIX}{execution_id}")


def manual_resolution_trade_id(execution_id: str) -> TradeID:
    """Return the stable trade identifier for one operator resolution.

    Parameters
    ----------
    execution_id : str
        Parent execution identity.

    Returns
    -------
    TradeID
        Deterministic identity that makes repeated submissions idempotent.
    """
    return TradeID(f"{_MANUAL_RESOLUTION_PREFIX}{execution_id}")


def manual_resolution_order_id(
    method: str,
    external_reference: str | None,
) -> OrderID:
    """Encode operator metadata in the existing optional order reference.

    Parameters
    ----------
    method : str
        Resolution method recorded by the operator.
    external_reference : str, optional
        Venue transaction, claim, or operator reference.

    Returns
    -------
    OrderID
        Encoded metadata stored without adding another persistence schema.
    """
    reference = external_reference.strip() if external_reference else ""
    return OrderID(f"{_MANUAL_RESOLUTION_PREFIX}{method}:{reference}")


def manual_resolution_metadata(trade: Trade) -> tuple[str, str | None] | None:
    """Decode method and external reference from a manual accounting trade.

    Parameters
    ----------
    trade : Trade
        Candidate trade loaded with an execution lifecycle.

    Returns
    -------
    tuple[str, str | None] | None
        Resolution method and optional reference, or ``None`` when the trade is
        not a valid manual resolution.
    """
    if trade.client_order_id is None or not str(trade.client_order_id).startswith(
        _MANUAL_RESOLUTION_PREFIX,
    ):
        return None
    encoded = str(trade.order_id or "")
    if not encoded.startswith(_MANUAL_RESOLUTION_PREFIX):
        return None
    method, separator, reference = encoded.removeprefix(
        _MANUAL_RESOLUTION_PREFIX,
    ).partition(":")
    if not separator or method not in {"manual_sale", "settlement"}:
        return None
    return method, reference or None


@dataclass(frozen=True, slots=True)
class PositionAccountingResult:
    """Return one WAC transition and its economic deltas.

    Attributes
    ----------
    position : Position
        Immutable position after applying the fill.
    realized_pnl : Decimal
        Gross realized PnL generated by this fill in settlement currency.
    fees : Money, optional
        Settlement-cost fee delta, when known.
    quality_flags : tuple of str
        Data-quality limitations carried by the transition.
    """

    position: Position
    realized_pnl: Decimal
    fees: Money | None
    quality_flags: tuple[str, ...]


@dataclass(frozen=True, slots=True)
class InventoryAccountingResult:
    """Return position changes produced by one confirmed inventory operation."""

    positions: tuple[Position, ...]
    realized_pnl: Decimal
    fees: Money | None
    quality_flags: tuple[str, ...]


class ExecutionAccounting:
    """Produce idempotent accounting events from one order observation."""

    def __init__(self, state: TradingState) -> None:
        self._state = state

    def record(
        self,
        command: SubmitOrder,
        previous: OrderSnapshot | None,
        current: OrderSnapshot,
        execution: ArbitrageExecutionJournal | None,
    ) -> tuple[ApplicationEvent, ...]:
        """Record an incremental fill or a late fee correction.

        Parameters
        ----------
        command : SubmitOrder
            Journaled order command associated with the cumulative snapshot.
        previous : OrderSnapshot, optional
            Previously applied cumulative snapshot for the same client order.
        current : OrderSnapshot
            New cumulative venue state.
        execution : ArbitrageExecutionJournal, optional
            Parent execution providing portfolio and strategy attribution.

        Returns
        -------
        tuple[ApplicationEvent, ...]
            Trade and position events for a positive fill delta, one trade
            correction for a newly known fee, or an empty tuple.
        """
        recorded: tuple[Trade, ...] = ()
        client_order_id = current.client_order_id or command.intent.client_order_id
        if previous is None and client_order_id is not None:
            # ponytail: replay-only scan; add a client-order trade index only if
            # journal size makes restart measurably slow.
            recorded = tuple(
                value
                for value in self._state.trades.values()
                if value.client_order_id == client_order_id
            )
        trade = _incremental_trade(
            command,
            previous,
            current,
            execution,
            recorded,
        )
        if trade is not None:
            existing = self._state.trades.get(trade.id)
            if existing is not None:
                if (
                    trade.fee is not None
                    and (
                        existing.fee != trade.fee
                        or existing.fee_settlement_cost != trade.fee_settlement_cost
                    )
                ):
                    corrected = replace(
                        existing,
                        fee=trade.fee,
                        fee_settlement_cost=trade.fee_settlement_cost,
                    )
                    return (_correction_event(self._state, existing, corrected),)
                return ()
            timings = self._state.timings.get(command.execution_id)
            if timings is not None and command.role in {"primary", "hedge"}:
                timings.mark_fill_recognized(
                    command.role,
                    str(command.venue_id),
                    time.monotonic_ns(),
                )
            return (
                TradeRecorded(trade),
                PositionUpdated(_next_position(self._state, trade)),
            )
        if current.fee is None:
            return ()
        trade_id = _trade_id(command, current)
        existing = self._state.trades.get(trade_id)
        if existing is None or (
            existing.fee == current.fee.charged
            and existing.fee_settlement_cost == current.fee.settlement_cost
        ):
            return ()
        corrected = replace(
            existing,
            fee=current.fee.charged,
            fee_settlement_cost=current.fee.settlement_cost,
        )
        return (_correction_event(self._state, existing, corrected),)


def is_settled_order(command: SubmitOrder, snapshot: OrderSnapshot) -> bool:
    """Return whether an order needs no further fill monitoring.

    Notes
    -----
    - Adapter-provided finality overrides both terminal status labels and legacy
      time-in-force inference. Removing an order from a book does not settle its
      in-flight matches. The venue adapter marks confirmed full fills final.
    """
    if snapshot.may_receive_more_fills is not None:
        return not snapshot.may_receive_more_fills
    if snapshot.is_terminal():
        return True
    return (
        command.intent.time_in_force in {TimeInForce.IOC, TimeInForce.FOK}
        and snapshot.status is OrderStatus.PARTIALLY_FILLED
    )


def _incremental_trade(
    command: SubmitOrder,
    previous: OrderSnapshot | None,
    current: OrderSnapshot,
    execution: ArbitrageExecutionJournal | None,
    recorded: tuple[Trade, ...] = (),
) -> Trade | None:
    """Build the positive fill delta between two cumulative snapshots."""
    previous_quantity = (
        previous.filled_quantity.value
        if previous is not None
        else sum((trade.quantity.value for trade in recorded), Decimal("0"))
    )
    delta_quantity = current.filled_quantity.value - previous_quantity
    if delta_quantity <= 0 or current.average_price is None:
        return None
    previous_notional = (
        previous_quantity * previous.average_price.value
        if previous is not None and previous.average_price is not None
        else sum(
            (trade.quantity.value * trade.price.value for trade in recorded),
            Decimal("0"),
        )
    )
    delta_price_value = (
        current.filled_quantity.value * current.average_price.value - previous_notional
    ) / delta_quantity
    if not Decimal("0") <= delta_price_value <= Decimal("1"):
        delta_price_value = current.average_price.value
    fee = None
    fee_settlement_cost = None
    if current.fee is not None:
        fee = _incremental_money(
            current.fee.charged,
            previous.fee.charged
            if previous is not None and previous.fee is not None
            else _recorded_money(
                tuple(trade.fee for trade in recorded),
                current.fee.charged,
            ),
        )
        fee_settlement_cost = _incremental_money(
            current.fee.settlement_cost,
            previous.fee.settlement_cost
            if previous is not None and previous.fee is not None
            else _recorded_money(
                tuple(trade.fee_settlement_cost for trade in recorded),
                current.fee.settlement_cost,
            ),
        )
    client_order_id = current.client_order_id or command.intent.client_order_id
    return Trade(
        id=_trade_id(command, current),
        order_id=current.order_id,
        client_order_id=client_order_id,
        contract_id=current.contract_id,
        venue_id=command.venue_id,
        side=current.side,
        quantity=Quantity(delta_quantity),
        price=Price(delta_price_value),
        executed_at=current.updated_at or Timestamp.now(),
        portfolio_id=(
            execution.portfolio_id
            if execution is not None
            else command.intent.portfolio_id
        ),
        strategy_id=(
            execution.strategy_id
            if execution is not None
            else command.intent.strategy_id
        ),
        fee=fee,
        fee_settlement_cost=fee_settlement_cost,
    )


def _trade_id(command: SubmitOrder, snapshot: OrderSnapshot) -> TradeID:
    """Return the stable identity for one cumulative fill observation."""
    client_order_id = snapshot.client_order_id or command.intent.client_order_id
    identity = (
        f"{command.venue_id}|{client_order_id}|{snapshot.order_id}|"
        f"{snapshot.filled_quantity.value}"
    )
    return TradeID(hashlib.sha256(identity.encode()).hexdigest()[:32])


def _incremental_money(current: Money, previous: Money | None) -> Money | None:
    """Return a non-negative cumulative money delta in one currency."""
    old_amount = (
        previous.amount if previous is not None and previous.currency == current.currency
        else Decimal("0")
    )
    delta = current.amount - old_amount
    return Money(delta, current.currency) if delta >= 0 else None


def _recorded_money(
    values: tuple[Money | None, ...],
    current: Money,
) -> Money:
    """Sum already recorded amounts in the current cumulative currency."""
    return Money(
        sum(
            (
                value.amount
                for value in values
                if value is not None and value.currency == current.currency
            ),
            Decimal("0"),
        ),
        current.currency,
    )


def apply_trade(
    current: Position | None,
    trade: Trade,
) -> PositionAccountingResult:
    """Apply one fill using weighted-average cost accounting.

    Parameters
    ----------
    current : Position, optional
        Existing venue-scoped position for the trade identity.
    trade : Trade
        Executed fill. ``BUY`` is positive inventory and ``SELL`` is negative.

    Returns
    -------
    PositionAccountingResult
        New position, realized-PnL delta, fee delta, and quality flags.

    Raises
    ------
    ValueError
        If an existing position belongs to another venue, portfolio, or
        contract, or if a position has no entry price.

    Notes
    -----
    - Same-direction fills blend at WAC.
    - Opposite-direction fills realize PnL against the current WAC; excess
      quantity opens the opposite side at the fill price.
    - Missing settlement fees are flagged and never treated as zero.
    """
    portfolio_id = trade.portfolio_id or _DEFAULT_PORTFOLIO_ID
    position_id = _position_id(trade.venue_id, portfolio_id, trade.contract_id)
    if current is not None:
        if (
            current.venue_id != trade.venue_id
            or current.portfolio_id != portfolio_id
            or current.contract_id != trade.contract_id
        ):
            raise ValueError("Trade identity does not match current position")

    signed = (
        trade.quantity.value
        if trade.side is OrderSide.BUY
        else -trade.quantity.value
    )
    current_signed = current.signed_quantity if current is not None else Decimal("0")
    current_average = current.average_price if current is not None else None
    if current_signed != 0 and current_average is None:
        raise ValueError("Open positions require average_price")

    updated_signed = current_signed + signed
    realized_delta = Decimal("0")
    if current_signed != 0 and current_average is not None and current_signed * signed < 0:
        closed_quantity = min(abs(current_signed), abs(signed))
        direction = Decimal("1") if current_signed > 0 else Decimal("-1")
        realized_delta = closed_quantity * direction * (
            trade.price.value - current_average.value
        )

    if updated_signed == 0:
        side = PositionSide.FLAT
        average = None
        mark = None
        opened_at = current.opened_at if current is not None else trade.executed_at
    else:
        side = PositionSide.LONG if updated_signed > 0 else PositionSide.SHORT
        flipped = current_signed != 0 and current_signed * updated_signed < 0
        same_direction = current_signed == 0 or current_signed * signed > 0
        if flipped or (not same_direction and abs(signed) > abs(current_signed)):
            average = trade.price
            mark = None
            opened_at = trade.executed_at
        elif same_direction and current_average is not None:
            average = Price(
                (
                    abs(current_signed) * current_average.value
                    + abs(signed) * trade.price.value
                )
                / (abs(current_signed) + abs(signed)),
            )
            mark = current.current_price if current is not None else None
            opened_at = current.opened_at if current is not None else trade.executed_at
        else:
            average = current_average or trade.price
            mark = current.current_price if current is not None else None
            opened_at = current.opened_at if current is not None else trade.executed_at

    flags = list(current.quality_flags if current is not None else ())
    if trade.fee_settlement_cost is None and "MISSING_FEES" not in flags:
        flags.append("MISSING_FEES")
    cumulative_fee = _add_fee(
        current.fees if current is not None else None,
        trade.fee_settlement_cost,
        flags,
    )
    position = Position(
        id=position_id,
        contract_id=trade.contract_id,
        portfolio_id=portfolio_id,
        quantity=Quantity(abs(updated_signed)),
        side=side,
        venue_id=trade.venue_id,
        average_price=average,
        current_price=mark,
        realized_pnl=(current.realized_pnl if current is not None else Decimal("0"))
        + realized_delta,
        fees=cumulative_fee,
        quality_flags=tuple(flags),
        opened_at=opened_at,
        updated_at=trade.executed_at,
    )
    return PositionAccountingResult(
        position=position,
        realized_pnl=realized_delta,
        fees=trade.fee_settlement_cost,
        quality_flags=tuple(flags),
    )


def apply_inventory_operation(
    current: dict[PositionID, Position],
    snapshot: InventoryOperationSnapshot,
) -> InventoryAccountingResult:
    """Apply one confirmed SPLIT, MERGE, or REDEEM to WAC positions.

    Parameters
    ----------
    current
        Current positions keyed by stable venue/portfolio/contract identity.
    snapshot
        Confirmed operation enriched from pre- and post-operation balances.

    Returns
    -------
    InventoryAccountingResult
        Updated positions, realized-PnL delta, separated fee, and quality flags.

    Raises
    ------
    ValueError
        If accounting context, quantities, or prices are inconsistent.

    Notes
    -----
    - Split basis is allocated uniformly across the created YES and NO tokens.
      The persisted request is authoritative because venue balance reads may lag
      a confirmed operation.
    - Merge and redeem never create synthetic shorts when opening inventory was
      absent from the journal; the missing basis is flagged instead.
    """
    reference = snapshot.reference
    before = reference.balance_before
    action = reference.action
    if before is None or action is None:
        raise ValueError("Inventory snapshot lacks accounting context")
    if before.yes_contract_id is None or before.no_contract_id is None:
        raise ValueError("Inventory snapshot lacks outcome contract ids")

    quantities = (
        snapshot.yes_quantity or Quantity(Decimal("0")),
        snapshot.no_quantity or Quantity(Decimal("0")),
    )
    contracts = (before.yes_contract_id, before.no_contract_id)
    if action is OutcomeInventoryAction.REDEEM:
        prices = (snapshot.yes_payout, snapshot.no_payout)
    else:
        operation_quantity = (
            reference.quantity or snapshot.quantity or Quantity(Decimal("0"))
        )
        quantities = (operation_quantity, operation_quantity)
        cash = (
            Money(reference.quantity.value, before.collateral.currency)
            if reference.quantity is not None
            else snapshot.collateral
        )
        total_quantity = sum((value.value for value in quantities), Decimal("0"))
        if cash is None or total_quantity <= 0:
            raise ValueError("Inventory operation lacks collateral or quantity")
        unit_price = cash.amount / total_quantity
        if not Decimal("0") <= unit_price <= Decimal("1"):
            raise ValueError("Inventory operation implies an invalid unit price")
        prices = (Price(unit_price), Price(unit_price))

    positions: list[Position] = []
    realized = Decimal("0")
    flags = list(snapshot.quality_flags)
    fee = snapshot.fee_settlement_cost
    fee_assigned = False
    for contract_id, quantity, price in zip(contracts, quantities, prices, strict=True):
        if quantity.value == 0:
            continue
        position_id = _position_id(
            reference.venue_id,
            reference.portfolio_id,
            contract_id,
        )
        existing = current.get(position_id)
        if price is None:
            position_fee = fee if not fee_assigned else None
            updated = _flag_position(
                existing,
                reference.venue_id,
                reference.portfolio_id,
                contract_id,
                snapshot.updated_at,
                "MISSING_PAYOUT_ALLOCATION",
                position_fee,
            )
            positions.append(updated)
            fee_assigned = fee_assigned or position_fee is not None
            if "MISSING_PAYOUT_ALLOCATION" not in flags:
                flags.append("MISSING_PAYOUT_ALLOCATION")
            continue

        applied_quantity = quantity
        if action is not OutcomeInventoryAction.SPLIT:
            available = (
                existing.quantity.value
                if existing is not None and existing.side is PositionSide.LONG
                else Decimal("0")
            )
            applied_quantity = Quantity(min(quantity.value, available))
            if applied_quantity.value < quantity.value:
                if "MISSING_OPENING_INVENTORY" not in flags:
                    flags.append("MISSING_OPENING_INVENTORY")
                if applied_quantity.value == 0:
                    position_fee = fee if not fee_assigned else None
                    positions.append(
                        _flag_position(
                            existing,
                            reference.venue_id,
                            reference.portfolio_id,
                            contract_id,
                            snapshot.updated_at,
                            "MISSING_OPENING_INVENTORY",
                            position_fee,
                        ),
                    )
                    fee_assigned = fee_assigned or position_fee is not None
                    continue

        trade_fee = fee if not fee_assigned else (
            Money(Decimal("0"), fee.currency) if fee is not None else None
        )
        result = apply_trade(
            existing,
            Trade(
                id=TradeID(f"inventory:{reference.operation_id}:{contract_id}"),
                contract_id=contract_id,
                venue_id=reference.venue_id,
                side=(
                    OrderSide.BUY
                    if action is OutcomeInventoryAction.SPLIT
                    else OrderSide.SELL
                ),
                quantity=applied_quantity,
                price=price,
                executed_at=snapshot.updated_at,
                portfolio_id=reference.portfolio_id,
                fee_settlement_cost=trade_fee,
            ),
        )
        fee_assigned = True
        merged_flags = tuple(dict.fromkeys((*result.position.quality_flags, *flags)))
        positions.append(replace(result.position, quality_flags=merged_flags))
        realized += result.realized_pnl

    return InventoryAccountingResult(
        positions=tuple(positions),
        realized_pnl=realized,
        fees=fee,
        quality_flags=tuple(flags),
    )


def _flag_position(
    current: Position | None,
    venue_id: VenueID,
    portfolio_id: PortfolioID,
    contract_id: ContractID,
    updated_at: Timestamp,
    flag: str,
    fee: Money | None = None,
) -> Position:
    """Carry an accounting limitation without inventing quantity or PnL."""
    flags = list(dict.fromkeys((*(current.quality_flags if current else ()), flag)))
    cumulative_fee = _add_fee(current.fees if current else None, fee, flags)
    if current is not None:
        return replace(
            current,
            fees=cumulative_fee,
            quality_flags=tuple(flags),
            updated_at=updated_at,
        )
    return Position(
        id=_position_id(venue_id, portfolio_id, contract_id),
        contract_id=contract_id,
        portfolio_id=portfolio_id,
        quantity=Quantity(Decimal("0")),
        side=PositionSide.FLAT,
        venue_id=venue_id,
        fees=cumulative_fee,
        quality_flags=tuple(flags),
        updated_at=updated_at,
    )


def _next_position(state: TradingState, trade: Trade) -> Position:
    """Return the position produced by one WAC transition."""
    portfolio_id = trade.portfolio_id or _DEFAULT_PORTFOLIO_ID
    current = state.positions.get(
        _position_id(trade.venue_id, portfolio_id, trade.contract_id),
    )
    return apply_trade(current, trade).position


def _position_with_corrected_fee(
    state: TradingState,
    original: Trade,
    corrected: Trade,
) -> Position:
    """Apply a late fee without rebuilding away inventory operations."""
    portfolio_id = corrected.portfolio_id or _DEFAULT_PORTFOLIO_ID
    position = state.positions.get(
        _position_id(corrected.venue_id, portfolio_id, corrected.contract_id),
    )
    if position is None:
        raise ValueError("Cannot correct fees without a current position")

    flags = list(position.quality_flags)
    fees = position.fees
    previous_fee = original.fee_settlement_cost
    if previous_fee is not None:
        if (
            fees is None
            or fees.currency != previous_fee.currency
            or fees.amount < previous_fee.amount
        ):
            fees = None
            if "INCONSISTENT_FEE_CURRENCY" not in flags:
                flags.append("INCONSISTENT_FEE_CURRENCY")
        else:
            fees = Money(fees.amount - previous_fee.amount, fees.currency)
    fees = _add_fee(fees, corrected.fee_settlement_cost, flags)
    return replace(position, fees=fees, quality_flags=tuple(flags))


def _correction_event(
    state: TradingState,
    original: Trade,
    replacement: Trade,
) -> AccountingCorrectionRecorded:
    """Represent an automatic late-fee update as an auditable correction."""
    fee_identity = (
        f"{replacement.fee}|{replacement.fee_settlement_cost}"
    ).encode()
    correction = AccountingCorrection(
        id=(
            f"fee-correction:{replacement.id}:"
            f"{hashlib.sha256(fee_identity).hexdigest()[:16]}"
        ),
        target_trade_id=replacement.id,
        original_trade=original,
        replacement_trade=replacement,
        resulting_position=_position_with_corrected_fee(state, original, replacement),
        reason="Venue reported a late cumulative fee update",
        recorded_at=Timestamp.now(),
    )
    return AccountingCorrectionRecorded(correction)


def rebuild_corrected_position(
    events: tuple[ApplicationEvent, ...],
    corrected: Trade,
) -> Position:
    """Replay durable economics with one trade replacement.

    Corrections are rare, so replaying the retained journal keeps the normal
    fill path small while preserving trades, inventory operations, and marks.
    """
    replacements: dict[TradeID, Trade] = {corrected.id: corrected}
    for event in events:
        if isinstance(event, AccountingCorrectionRecorded):
            replacements[event.correction.target_trade_id] = (
                event.correction.replacement_trade
            )
    replacements[corrected.id] = corrected

    positions: dict[PositionID, Position] = {}
    seen_trades: set[TradeID] = set()
    seen_operations: set[object] = set()
    for event in events:
        if isinstance(event, TradeRecorded):
            if event.trade.id in seen_trades:
                continue
            seen_trades.add(event.trade.id)
            trade = replacements.get(event.trade.id, event.trade)
            portfolio_id = trade.portfolio_id or _DEFAULT_PORTFOLIO_ID
            position_id = _position_id(
                trade.venue_id,
                portfolio_id,
                trade.contract_id,
            )
            positions[position_id] = apply_trade(
                positions.get(position_id),
                trade,
            ).position
        elif isinstance(event, InventoryOperationRecorded):
            snapshot = (
                event.record
                if isinstance(event.record, InventoryOperationSnapshot)
                else event.record.snapshot
            )
            if (
                snapshot is None
                or snapshot.status is not InventoryOperationStatus.CONFIRMED
                or snapshot.reference.operation_id in seen_operations
            ):
                continue
            seen_operations.add(snapshot.reference.operation_id)
            try:
                result = apply_inventory_operation(positions, snapshot)
            except ValueError:
                continue
            for position in result.positions:
                positions[position.id] = position
        elif isinstance(event, MarketSettlementRecorded):
            settlement = event.settlement
            for contract_id, price in (
                (settlement.yes_contract_id, settlement.yes_payout),
                (settlement.no_contract_id, settlement.no_payout),
            ):
                position_id = _position_id(
                    settlement.venue_id,
                    corrected.portfolio_id or _DEFAULT_PORTFOLIO_ID,
                    contract_id,
                )
                position = positions.get(position_id)
                if position is not None and position.is_open():
                    positions[position_id] = position.with_mark(
                        price,
                        settlement.observed_at,
                    )

    target_id = _position_id(
        corrected.venue_id,
        corrected.portfolio_id or _DEFAULT_PORTFOLIO_ID,
        corrected.contract_id,
    )
    try:
        return positions[target_id]
    except KeyError as error:
        raise ValueError("Corrected trade is not present in retained journal") from error


def _position_id(
    venue_id: VenueID,
    portfolio_id: PortfolioID,
    contract_id: ContractID,
) -> PositionID:
    """Build a collision-free position identity across venues."""
    return PositionID(f"{venue_id}:{portfolio_id}:{contract_id}")


def _add_fee(
    current: Money | None,
    delta: Money | None,
    flags: list[str],
) -> Money | None:
    """Add fees only when settlement currencies agree."""
    if current is None:
        return delta
    if delta is None:
        return current
    if current.currency != delta.currency:
        if "INCONSISTENT_FEE_CURRENCY" not in flags:
            flags.append("INCONSISTENT_FEE_CURRENCY")
        return None
    return Money(current.amount + delta.amount, current.currency)
